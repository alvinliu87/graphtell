/**
 * Minimal i18n layer.
 *
 * Design notes:
 *
 * * **English is the source language.** UI copy is written in English at the
 *   call site (`t('Compose prompt')`), and `zh-CN` only carries an override
 *   table `English -> Chinese`. A missing translation therefore degrades to
 *   readable English instead of a raw key or a blank screen.
 * * **Stable identifiers use semantic keys.** Node / edge `kind`s and build
 *   diagnostic `code`s are open-ended strings produced by the Rust core, so they
 *   are looked up under keys such as `edge.Calls` or `diag.UnresolvedLink.title`.
 *   Adding a language never requires recompiling the Rust core (OCP).
 * * Unknown keys fall back to the key itself, both with and without a
 *   `LocaleProvider`, so unit tests that render components bare keep working.
 */

