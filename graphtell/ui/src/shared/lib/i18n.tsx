function readStoredLang(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (v === 'en-US' || v === 'zh-CN') return v;
  } catch {
    /* localStorage unavailable (SSR / privacy mode) — fall back to default. */
  }
  return DEFAULT_LANG;
}

export interface LocaleApi {
  lang: Lang;
  setLang: (l: Lang) => void;
  /** Unknown keys fall back to the key itself so nothing ever renders blank. */
  t: (key: string) => string;
}

/** Used when components are rendered without a `LocaleProvider` (unit tests). */
const noProvider: LocaleApi = {
  lang: DEFAULT_LANG,
  setLang: () => {},
  t: (k: string) => dict[DEFAULT_LANG][k] ?? k,
};

/** Most recently activated language; lets non-component code translate once. */
let currentLang: Lang = DEFAULT_LANG;

/**
 * Translate outside of React (e.g. `ide.ts`, `http.ts` helpers) using the
 * language that was last activated by the provider.
 */
export function translate(k: string): string {
  return dict[currentLang][k] ?? dict[DEFAULT_LANG][k] ?? k;
}

const LocaleContext = createContext<LocaleApi>(noProvider);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readStoredLang);
  useEffect(() => {
    currentLang = lang;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      /* ignore */
    }
  }, [lang]);

  const api = useMemo<LocaleApi>(
    () => ({
      lang,
      setLang: setLangState,
      t: (k: string) => dict[lang][k] ?? dict[DEFAULT_LANG][k] ?? k,
    }),
    [lang],
  );

  return <LocaleContext.Provider value={api}>{children}</LocaleContext.Provider>;
}

export function useLocale(): LocaleApi {
  return useContext(LocaleContext);
}

/**
 * Human-readable label for an edge kind.
 *
 * In the folded view a user and a resource are joined by a **single** edge
 * (write wins over read); the suppressed half is reported by the backend in
 * `also_kinds` (`WritesDb` + `['ReadsDb']` = this place both reads and writes).
 * In that case the combined predicate must be used — reporting only "reads" or
 * only "writes" would both be wrong.
 *
 * Combined keys concatenate the kinds in **lexicographic order**
 * (`ReadsDb+WritesDb`), independent of how `also_kinds` happens to be ordered.
 * When no combined entry exists we fall back to the single-kind label.
 */
export function edgeKindLabel(
  t: (k: string) => string,
  kind: string,
  also: string[] = [],
): string {
  const single = `edge.${kind}`;
  if (!also.length) {
    return t(single);
  }
  const both = `edge.${[kind, ...also].sort().join('+')}`;
  const v = t(both);
  return v === both ? t(single) : v;
}
